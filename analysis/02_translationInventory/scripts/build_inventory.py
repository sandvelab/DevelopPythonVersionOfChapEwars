"""Join the mechanically extracted R calls with the authored R -> Python mapping.

Inputs:  results/r_calls.tsv      (extract_r_calls.R: every call site, from R's parser)
         scripts/call_mapping.tsv  (authored: Python counterpart, status, batch, note)
         results/inla_defaults.tsv (inla_defaults.R: the INLA settings the fit depends on)
Outputs: results/translation_inventory.md  the inventory, one row per distinct call, grouped
                                           by status, with every call site's file:line
         results/coverage.tsv              status counts
         results/unmapped.txt              calls with no mapping row, and mapping rows that
                                           match no call; both must be empty
Exits non-zero if either list in unmapped.txt is non-empty.

Usage: build_inventory.py <node_dir>
"""

import sys
from pathlib import Path

import pandas as pd

node = Path(sys.argv[1])
calls = pd.read_csv(node / "results/r_calls.tsv", sep="\t", dtype=str)
mapping = pd.read_csv(node / "scripts/call_mapping.tsv", sep="\t", dtype=str, keep_default_na=False)
defaults = pd.read_csv(node / "results/inla_defaults.tsv", sep="\t", dtype=str, keep_default_na=False)

distinct = (calls.groupby("call")
            .agg(kind=("kind", "first"), supplied_by=("supplied_by", "first"),
                 sites=("line", lambda s: None), n=("line", "size"))
            .reset_index())
sites = calls.assign(site=calls["file"] + ":" + calls["line"]).groupby("call")["site"].apply(
    lambda s: ", ".join(sorted(set(s), key=lambda x: (x.split(":")[0], int(x.split(":")[1])))))
distinct["sites"] = distinct["call"].map(sites)

unmapped = sorted(set(distinct["call"]) - set(mapping["call"]))
orphans = sorted(set(mapping["call"]) - set(distinct["call"]))
(node / "results/unmapped.txt").write_text(
    "calls without a mapping row:\n" + "".join(f"  {c}\n" for c in unmapped)
    + "mapping rows matching no call:\n" + "".join(f"  {c}\n" for c in orphans))

inv = distinct.merge(mapping, on="call", how="left")
ORDER = ["gap-inference", "gap-port", "counterpart-verify", "port", "direct", "not-needed"]
TITLE = {
    "gap-inference": "Gaps: the inference engine (an alternatives node, batches 7-10)",
    "gap-port": "Gaps: model pieces with no trustworthy Python counterpart (parallel ports, verified against R)",
    "counterpart-verify": "Python counterparts that exist but are verified against R before use",
    "port": "Functions of the model's own code, ported line by line",
    "direct": "Standard data handling with a direct Python equivalent",
    "not-needed": "Not needed in the Python service (I/O, logging, service plumbing)",
}
cov = inv["status"].value_counts().reindex(ORDER, fill_value=0)
cov.rename_axis("status").reset_index(name="distinct_calls").to_csv(node / "results/coverage.tsv", sep="\t", index=False)


def cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


out = ["# Translation inventory: every R call in the EWARS model, and its Python counterpart", "",
       "Generated by `analysis/02_translationInventory/scripts/build_inventory.py` from "
       "`results/r_calls.tsv` (R's parser, run in the reference image), "
       "`scripts/call_mapping.tsv` and `results/inla_defaults.tsv`. Do not edit.", "",
       f"{len(calls)} call sites, {len(distinct)} distinct calls (formula terms included) in "
       "`predict.R`, `lib.R` and `train.R` of chapkit_ewars_model @ 964eea8b. "
       f"Unmapped: {len(unmapped)}.", "",
       "| Status | Distinct calls |", "|---|---|"]
out += [f"| {s} | {cov[s]} |" for s in ORDER]
for s in ORDER:
    part = inv[inv["status"] == s].sort_values("call")
    if part.empty:
        continue
    out += ["", f"## {TITLE[s]}", "", "| R call | Supplied by | Python | Batch | Note | Call sites |",
            "|---|---|---|---|---|---|"]
    out += [f"| `{cell(r.call)}` | {cell(r.supplied_by)} | {cell(r.python)} | {cell(r.batch)} | {cell(r.note)} | {cell(r.sites)} |"
            for r in part.itertuples()]
out += ["", "## The INLA settings the fit depends on", "",
        "Read from the installed INLA 25.10.19 in the reference image (`results/inla_defaults.tsv`).", "",
        "| Group | Setting | Value | Source |", "|---|---|---|---|"]
out += [f"| {cell(r.group)} | {cell(r.setting)} | `{cell(r.value)}` | {cell(r.source)} |" for r in defaults.itertuples()]
(node / "results/translation_inventory.md").write_text("\n".join(out) + "\n")
print(cov.to_string())
print(f"unmapped: {len(unmapped)}, orphans: {len(orphans)}")
sys.exit(1 if unmapped or orphans else 0)
