"""Render the translation ledgers into the two human-facing documents.

Reads AI-internal/translation-log/{judgment_calls,challenges}.json (append-only ledgers)
and writes AI-generated/translation-record/{judgment-calls,challenges}.md: a short main
part (one line per entry) followed by an appendix with the details. Never hand-edit the
outputs; edit the ledgers by appending entries, then re-run this script.

CLI:  .venv/bin/python AI-internal/useful-scripts/render_translation_record.py
API:  render(root: pathlib.Path) -> list[pathlib.Path]
"""
import json
import pathlib
import sys


def _jc(entries):
    out = ["# Judgment calls in the R → Python translation", "",
           "Generated by `AI-internal/useful-scripts/render_translation_record.py` from "
           "`AI-internal/translation-log/judgment_calls.json`. Do not edit.", "",
           "| ID | Area | Call | Choice | Agency |", "|---|---|---|---|---|"]
    for e in entries:
        out.append(f"| [{e['id']}](#{e['id'].lower()}) | {e['area']} | {e['call']} | {e['choice']} | {e['agency']} |")
    out += ["", "## Appendix — details", ""]
    for e in entries:
        out += [f"### {e['id']}", "",
                f"- **Call**: {e['call']}", f"- **Choice**: {e['choice']}",
                f"- **Alternatives considered**: {e['alternatives']}",
                f"- **Basis**: {e['basis']}",
                f"- **Agency**: {e['agency']}; information: {e.get('information', '-')}",
                f"- **Where recorded**: {e['where']}",
                f"- **Does it move the conclusion?** {e['matters']}",
                f"- **Settled**: {e['date']}, batch {e['batch']}", ""]
    return "\n".join(out)


def _ch(entries):
    out = ["# Challenges met in the R → Python translation", "",
           "Generated by `AI-internal/useful-scripts/render_translation_record.py` from "
           "`AI-internal/translation-log/challenges.json`. Do not edit.", "",
           "| ID | Challenge | How it was handled | Status |", "|---|---|---|---|"]
    for e in entries:
        out.append(f"| [{e['id']}](#{e['id'].lower()}) | {e['challenge']} | {e['solution']} | {e['status']} |")
    out += ["", "## Appendix — details", ""]
    for e in entries:
        out += [f"### {e['id']}", "", e["details"], "",
                f"Raised {e['date']}, batch {e['batch']}.", ""]
    return "\n".join(out)


def render(root):
    log = root / "AI-internal/translation-log"
    dst = root / "AI-generated/translation-record"
    dst.mkdir(parents=True, exist_ok=True)
    pairs = [(_jc, "judgment_calls.json", "judgment-calls.md"),
             (_ch, "challenges.json", "challenges.md")]
    written = []
    for fn, src, out in pairs:
        p = dst / out
        p.write_text(fn(json.loads((log / src).read_text())) + "\n")
        written.append(p)
    return written


if __name__ == "__main__":
    root = pathlib.Path(__file__).resolve().parents[2]
    for p in render(root):
        print(p.relative_to(root))
    sys.exit(0)
